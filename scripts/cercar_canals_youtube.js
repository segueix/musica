'use strict';

const fs = require('fs');
const path = require('path');

const FILE = path.join(process.cwd(), 'data', 'artistes-musica.json');
const SEARCH_URL = 'https://www.googleapis.com/youtube/v3/search';
const CHANNELS_URL = 'https://www.googleapis.com/youtube/v3/channels';
const DEFAULT_BATCH = 25;
const MAX_BATCH = 25;
const DAILY_SEARCH_CAP = 80;
const RECHECK_DAYS = 30;
const CHANNEL_ID_RE = /^UC[A-Za-z0-9_-]{22}$/;

function argNumber(name, fallback) {
    const prefix = '--' + name + '=';
    const found = process.argv.find((arg) => arg.startsWith(prefix));
    if (!found) return fallback;
    const value = Number.parseInt(found.slice(prefix.length), 10);
    return Number.isFinite(value) && value > 0 ? value : fallback;
}

function normalizeText(value) {
    return String(value || '')
        .normalize('NFD')
        .replace(/\p{Diacritic}/gu, '')
        .toLowerCase()
        .replace(/&/g, ' i ')
        .replace(/[^a-z0-9]+/g, ' ')
        .trim()
        .replace(/\s+/g, ' ');
}

function compact(value) {
    return normalizeText(value).replace(/\s+/g, '');
}

function stripParenthetical(value) {
    return String(value || '').replace(/\s*\([^)]*\)\s*$/g, '').trim();
}

function artistForms(name, aliases) {
    return [...new Set([name, stripParenthetical(name), ...(aliases || [])]
        .map(normalizeText)
        .filter(Boolean))];
}

function stripDecorations(title) {
    return normalizeText(title)
        .replace(/\b(canal oficial|official channel|oficial|official|music)\b/g, ' ')
        .replace(/\s+/g, ' ')
        .trim();
}

function isTopicChannel(title, description) {
    return /(?:^|\s)-?\s*topic\s*$/i.test(String(title || ''))
        || /auto-generated by youtube/i.test(String(description || ''));
}

function baseTopicTitle(title) {
    return normalizeText(String(title || '').replace(/\s*-\s*topic\s*$/i, ''));
}

function scoreCandidate(artist, channel, rank) {
    const forms = artistForms(artist.name, artist.aliases);
    const title = normalizeText(channel.title);
    const stripped = stripDecorations(channel.title);
    const topic = isTopicChannel(channel.title, channel.description);
    const topicBase = baseTopicTitle(channel.title);
    const handle = compact(String(channel.handle || '').replace(/^@/, ''));
    const formCompacts = forms.map(compact).filter(Boolean);
    const canonical = normalizeText(artist.name);
    const exactTitle = forms.includes(title);
    const decoratedExact = forms.includes(stripped);
    const topicExact = topic && forms.includes(topicBase);
    const canonicalExact = title === canonical;
    const canonicalDecorated = stripped === canonical;
    const canonicalTopicExact = topic && topicBase === canonical;
    const handleExact = formCompacts.some((form) => form.length >= 5 && handle === form);
    const handleContains = formCompacts.some((form) =>
        form.length >= 6 && handle && (handle.includes(form) || form.includes(handle))
    );
    const officialText = /\b(official|oficial|canal oficial)\b/i.test(
        String(channel.title || '') + ' ' + String(channel.description || '')
    );
    const autoGenerated = /auto-generated by youtube/i.test(String(channel.description || ''));

    let score = 0;
    const reasons = [];

    if (topicExact) {
        score += 80;
        reasons.push('nom exacte de canal Topic');
    } else if (exactTitle) {
        score += 70;
        reasons.push('nom exacte');
    } else if (decoratedExact) {
        score += 65;
        reasons.push('nom exacte traient oficial');
    } else if (forms.some((form) => form.length >= 6 && (title.includes(form) || form.includes(title)))) {
        score += 35;
        reasons.push('nom parcial');
    }

    if (handleExact) {
        score += 25;
        reasons.push('handle exacte');
    } else if (handleContains) {
        score += 18;
        reasons.push('handle coincident');
    }

    if (officialText) {
        score += 10;
        reasons.push('marca oficial');
    }
    if (autoGenerated) {
        score += 15;
        reasons.push('auto-generat per YouTube');
    }
    if (rank === 0) {
        score += 5;
        reasons.push('primer resultat');
    }

    return {
        score,
        reasons,
        topic,
        topicExact,
        autoGenerated,
        exactTitle,
        decoratedExact,
        canonicalExact,
        canonicalDecorated,
        canonicalTopicExact,
        handleExact,
        handleMatch: handleExact || handleContains
    };
}

function isGenericArtistName(name) {
    const normalized = normalizeText(stripParenthetical(name));
    return !normalized.includes(' ') && compact(normalized).length <= 7;
}

function decideAutoAccept(artist, scored) {
    if (!scored.length) return null;
    const best = scored[0];
    const second = scored[1];
    const margin = best.score - (second ? second.score : 0);

    if (best.meta.canonicalTopicExact && best.meta.autoGenerated && best.score >= 95 && margin >= 10) {
        return best;
    }

    const hasDisambiguation = stripParenthetical(artist.name) !== String(artist.name || '').trim();

    if (
        !hasDisambiguation
        && !isGenericArtistName(artist.name)
        && (best.meta.canonicalExact || best.meta.canonicalDecorated)
        && best.meta.handleExact
        && best.score >= 100
        && margin >= 15
    ) {
        return best;
    }

    return null;
}

function pacificDateKey(value) {
    const date = value instanceof Date ? value : new Date(value);
    if (!Number.isFinite(date.getTime())) return null;
    const parts = new Intl.DateTimeFormat('en-US', {
        timeZone: 'America/Los_Angeles',
        year: 'numeric',
        month: '2-digit',
        day: '2-digit'
    }).formatToParts(date);
    const get = (type) => parts.find((part) => part.type === type)?.value;
    return get('year') + '-' + get('month') + '-' + get('day');
}

function daysSince(value) {
    if (!value) return Infinity;
    const time = new Date(value).getTime();
    if (!Number.isFinite(time)) return Infinity;
    return (Date.now() - time) / 86400000;
}

async function apiJson(url, apiKey) {
    url.searchParams.set('key', apiKey);
    const response = await fetch(url);
    const body = await response.text();

    if (!response.ok) {
        let reason = '';
        try {
            const parsed = JSON.parse(body);
            reason = parsed?.error?.errors?.[0]?.reason || parsed?.error?.message || '';
        } catch (_) {
            reason = body.slice(0, 250);
        }
        const error = new Error('YouTube API HTTP ' + response.status + ': ' + (reason || 'error'));
        error.status = response.status;
        error.reason = reason;
        throw error;
    }

    return JSON.parse(body);
}

async function searchChannels(name, apiKey) {
    const url = new URL(SEARCH_URL);
    url.searchParams.set('part', 'snippet');
    url.searchParams.set('type', 'channel');
    url.searchParams.set('maxResults', '10');
    url.searchParams.set('q', name);
    return apiJson(url, apiKey);
}

async function channelDetails(ids, apiKey) {
    if (!ids.length) return [];
    const url = new URL(CHANNELS_URL);
    url.searchParams.set('part', 'snippet,statistics');
    url.searchParams.set('id', ids.join(','));
    const payload = await apiJson(url, apiKey);
    return payload.items || [];
}

function toSearchCandidate(item, rank, artist, now) {
    const channel = {
        id: item.id,
        title: item.snippet?.title || '',
        description: String(item.snippet?.description || '').slice(0, 350),
        handle: item.snippet?.customUrl?.startsWith('@') ? item.snippet.customUrl : null,
        subscriberCount: Number(item.statistics?.subscriberCount || 0),
        thumbnail: item.snippet?.thumbnails?.medium?.url
            || item.snippet?.thumbnails?.default?.url
            || null
    };
    const meta = scoreCandidate(artist, channel, rank);
    return {
        id: channel.id,
        title: channel.title,
        handle: channel.handle,
        description: channel.description,
        subscriberCount: channel.subscriberCount,
        thumbnail: channel.thumbnail,
        score: meta.score,
        reasons: meta.reasons,
        suggestedType: meta.topic ? 'topic' : 'official',
        discoveredAt: now,
        meta
    };
}

function publicCandidate(candidate) {
    const copy = { ...candidate };
    delete copy.meta;
    return copy;
}

async function main() {
    const apiKey = process.env.YOUTUBE_API_KEY_SERVER;
    if (!apiKey) {
        console.error('❌ Falta el secret YOUTUBE_API_KEY_SERVER.');
        process.exit(1);
    }

    const data = JSON.parse(fs.readFileSync(FILE, 'utf8'));
    const todayPT = pacificDateKey(new Date());
    const alreadyUsedToday = data.artists.filter((artist) =>
        pacificDateKey(artist.enrichment?.youtubeSearch?.checkedAt) === todayPT
    ).length;

    const requested = Math.min(argNumber('limit', DEFAULT_BATCH), MAX_BATCH);
    const allowance = Math.max(0, DAILY_SEARCH_CAP - alreadyUsedToday);
    const runLimit = Math.min(requested, allowance);

    if (runLimit <= 0) {
        console.log('🛑 Cerca YouTube: límit intern diari assolit (' + alreadyUsedToday + '/' + DAILY_SEARCH_CAP + ').');
        return;
    }

    const targets = data.artists
        .filter((artist) => {
            if (artist.reviewStatus === 'rebutjat') return false;
            if (artist.youtube?.channels?.length) return false;
            const checkedAt = artist.enrichment?.youtubeSearch?.checkedAt;
            return !checkedAt || daysSince(checkedAt) >= RECHECK_DAYS;
        })
        .slice(0, runLimit);

    if (!targets.length) {
        console.log('✅ Cerca YouTube: no hi ha artistes pendents de cerca.');
        return;
    }

    let searches = 0;
    let autoAccepted = 0;
    let withCandidates = 0;
    let noResults = 0;
    let errors = 0;
    let quotaStopped = false;

    for (const artist of targets) {
        const now = new Date().toISOString();
        artist.youtube ||= { channels: [] };
        artist.youtube.channels ||= [];
        artist.enrichment ||= {};

        try {
            const searchName = ['Mazoni','Motoclus'].includes(artist.name) ? artist.name + ' - Topic' : artist.name;
            const search = await searchChannels(searchName, apiKey);
            searches += 1;
            const ids = (search.items || [])
                .map((item) => item.id?.channelId)
                .filter((id) => CHANNEL_ID_RE.test(id));

            const details = await channelDetails(ids, apiKey);
            const detailMap = new Map(details.map((item) => [item.id, item]));
            const scored = ids
                .map((id, rank) => detailMap.get(id) ? toSearchCandidate(detailMap.get(id), rank, artist, now) : null)
                .filter(Boolean)
                .sort((a, b) => b.score - a.score);

            artist.youtube.searchCandidates = scored.map(publicCandidate);
            const accepted = decideAutoAccept(artist, scored);

            artist.enrichment.youtubeSearch = {
                checkedAt: now,
                status: accepted ? 'autoacceptat' : scored.length ? 'candidats' : 'sense-resultats',
                query: searchName,
                resultCount: scored.length,
                bestScore: scored[0]?.score || 0,
                autoAcceptedId: accepted?.id || null
            };

            if (accepted) {
                artist.youtube.channels.push({
                    id: accepted.id,
                    handle: accepted.handle,
                    name: accepted.title,
                    type: accepted.suggestedType,
                    primary: true
                });
                artist.sources = [...new Set([...artist.sources, 'youtube:search-auto'])];
                artist.confidence = 'alta';
                artist.lastChecked = now;
                autoAccepted += 1;
                console.log('✅ ' + artist.name + ': autoacceptat ' + accepted.title + ' (' + accepted.id + '), score ' + accepted.score + '.');
            } else if (scored.length) {
                withCandidates += 1;
                console.log('🔎 ' + artist.name + ': ' + scored.length + ' candidats; millor score ' + scored[0].score + '.');
            } else {
                noResults += 1;
                console.log('⚪ ' + artist.name + ': sense canals candidats.');
            }
        } catch (error) {
            const reason = String(error.reason || error.message || '');
            if (error.status === 403 && /quota|limit/i.test(reason)) {
                quotaStopped = true;
                console.warn('🛑 Quota de cerca aturada després de ' + searches + ' cerques: ' + reason);
                break;
            }

            errors += 1;
            artist.enrichment.youtubeSearch = {
                checkedAt: now,
                status: 'error',
                query: artist.name,
                resultCount: 0,
                bestScore: 0,
                autoAcceptedId: null,
                error: String(error.message || error).slice(0, 300)
            };
            console.warn('⚠️ ' + artist.name + ': ' + error.message);
        }
    }

    if (searches || autoAccepted || withCandidates || noResults || errors) {
        data.updatedAt = new Date().toISOString();
        fs.writeFileSync(FILE, JSON.stringify(data, null, 2) + '\n');
    }

    console.log(
        '📊 Cerca YouTube: ' + searches + ' search.list; ' + autoAccepted + ' autoacceptats; '
        + withCandidates + ' amb candidats; ' + noResults + ' sense resultats; ' + errors + ' errors'
        + (quotaStopped ? '; aturat per quota.' : '.')
    );
}

module.exports = {
    normalizeText,
    scoreCandidate,
    decideAutoAccept,
    isGenericArtistName,
    pacificDateKey
};

if (require.main === module) {
    main().catch((error) => {
        console.error('❌ ' + (error.stack || error.message));
        process.exit(1);
    });
}

