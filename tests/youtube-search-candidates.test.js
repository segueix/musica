import { describe, it, expect } from 'vitest';
import searchModule from '../scripts/cercar_canals_youtube.js';

const {
    scoreCandidate,
    decideAutoAccept,
    isGenericArtistName,
    pacificDateKey
} = searchModule;

function scored(artist, channels) {
    return channels
        .map((channel, index) => {
            const meta = scoreCandidate(artist, channel, index);
            return {
                ...channel,
                score: meta.score,
                meta,
                suggestedType: meta.topic ? 'topic' : 'official'
            };
        })
        .sort((a, b) => b.score - a.score);
}

describe('cerca controlada de canals YouTube', () => {
    it('autoaccepta un canal oficial amb nom i handle inequívocs', () => {
        const artist = { name: 'Els Pets', aliases: [] };
        const candidates = scored(artist, [
            { id: 'UC123', title: 'Els Pets', handle: '@elspets', description: 'Canal oficial' },
            { id: 'UC456', title: 'Fans dels Pets', handle: '@fanselspets', description: '' }
        ]);
        expect(decideAutoAccept(artist, candidates)?.id).toBe('UC123');
    });

    it('no autoaccepta noms genèrics curts', () => {
        const artist = { name: 'Berta', aliases: [] };
        const candidates = scored(artist, [
            { id: 'UC123', title: 'Berta', handle: '@berta', description: 'Canal oficial' }
        ]);
        expect(isGenericArtistName('Berta')).toBe(true);
        expect(decideAutoAccept(artist, candidates)).toBe(null);
    });

    it('autoaccepta un Topic inequívoc auto-generat per YouTube', () => {
        const artist = { name: 'Strombers', aliases: [] };
        const candidates = scored(artist, [
            { id: 'UC123', title: 'Strombers - Topic', handle: null, description: 'Auto-generated by YouTube.' }
        ]);
        expect(decideAutoAccept(artist, candidates)?.id).toBe('UC123');
    });

    it('calcula el dia segons hora del Pacífic', () => {
        expect(pacificDateKey(new Date('2026-09-25T06:30:00Z'))).toBe('2026-09-24');
        expect(pacificDateKey(new Date('2026-09-25T08:30:00Z'))).toBe('2026-09-25');
    });
});
