import { createRequire } from 'node:module';
import { describe, expect, it } from 'vitest';

const { extractOriginalYear, parseManualDates, stampOriginalYear } = createRequire(import.meta.url)(
    '../scripts/lib/any_original_musical.js'
);

const topic = (extra = '') =>
    `Provided to YouTube by Segell\n\nAlegria · Artista\n\n℗ 2019 Segell\n\nReleased on: 2009-05-03\n${extra}\nAuto-generated by YouTube.`;

describe('any original de la descripció automàtica', () => {
    it('«Released on» és evidència d’alta confiança amb data completa', () => {
        expect(extractOriginalYear(topic())).toEqual({
            year: 2009,
            date: '2009-05-03',
            source: 'released-on',
            confidence: 'alta',
        });
    });

    it('sense «Released on», el ℗ dona l’any de la gravació amb confiança mitjana', () => {
        expect(extractOriginalYear('Provided to YouTube by X\n℗ 2014 Label')).toEqual({
            year: 2014,
            date: null,
            source: 'p-line',
            confidence: 'mitjana',
        });
    });

    it('no inventa res sense evidència ni accepta anys impossibles', () => {
        expect(extractOriginalYear('Nou videoclip! Ja disponible.')).toBeNull();
        expect(extractOriginalYear('Released on: 1650-01-01', { currentYear: 2026 })).toBeNull();
        expect(extractOriginalYear('Released on: 2099-01-01', { currentYear: 2026 })).toBeNull();
        expect(extractOriginalYear('')).toBeNull();
    });

    it('l’estampat és idempotent i retira l’any si l’evidència desapareix', () => {
        const video = { id: 'a', description: topic() };
        expect(stampOriginalYear(video, new Map())).toBe(true);
        expect(video).toMatchObject({
            originalYear: 2009,
            originalDate: '2009-05-03',
            originalYearSource: 'released-on',
        });
        expect(stampOriginalYear(video, new Map())).toBe(false);
        video.description = 'Sense dades';
        expect(stampOriginalYear(video, new Map())).toBe(true);
        expect(video.originalYear).toBeUndefined();
    });

    it('una excepció verificada per cançó mana sobre l’evidència automàtica', () => {
        const manual = parseManualDates({ songs: { a: { year: 2025, note: 'verificat' }, b: { year: 1200 } } });
        expect([...manual.keys()]).toEqual(['a']);
        const video = { id: 'a', description: topic() };
        stampOriginalYear(video, manual);
        expect(video).toMatchObject({
            originalYear: 2025,
            originalYearSource: 'manual',
            originalYearConfidence: 'alta',
        });
    });
});
