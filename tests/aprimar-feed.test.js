import { describe, it, expect } from 'vitest';
import { createRequire } from 'module';

const require = createRequire(import.meta.url);
const {
    DESCRIPTION_LIMIT,
    CUT_MARK,
    shortDescription,
    slimFeedVideo,
    slimFeed,
    serializeFeed,
} = require('../scripts/lib/aprimar_feed.js');
const { extractOriginalYear } = require('../scripts/lib/any_original_musical.js');

const TOPIC = [
    'Provided to YouTube by RGB Suports',
    '',
    'Les Tietes · Companyia Elèctrica Dharma',
    '',
    'Recordant Josep Fortuny',
    '',
    ...Array.from({ length: 20 }, (_, i) => `Composer: Compositor número ${i}`),
    '',
    '℗ 1998 RGB Suports',
    '',
    'Released on: 1998-03-27',
    '',
    'Auto-generated by YouTube.',
].join('\n');

describe('aprimar el feed', () => {
    it('deixa igual una descripció curta', () => {
        expect(shortDescription('Videoclip oficial.')).toBe('Videoclip oficial.');
        expect(shortDescription('')).toBe('');
        expect(shortDescription(undefined)).toBe('');
    });

    it('retalla una descripció llarga i hi conserva les línies de l’any original', () => {
        const short = shortDescription(TOPIC);
        expect(short.length).toBeLessThan(TOPIC.length);
        expect(short.indexOf(CUT_MARK)).toBeLessThanOrEqual(DESCRIPTION_LIMIT);
        expect(short.startsWith('Provided to YouTube by RGB Suports\n\nLes Tietes · Companyia Elèctrica Dharma')).toBe(
            true
        );
        expect(short).toContain('℗ 1998 RGB Suports');
        expect(short).toContain('Released on: 1998-03-27');
        expect(extractOriginalYear(short)).toEqual(extractOriginalYear(TOPIC));
    });

    it('és idempotent', () => {
        const once = shortDescription(TOPIC);
        expect(shortDescription(once)).toBe(once);
        const video = slimFeedVideo({ id: 'a', channelId: 'UC1', sourceChannelId: 'UC1', description: TOPIC });
        expect(slimFeedVideo(video)).toEqual(video);
    });

    it('treu els camps que el client no llegeix i conserva els que sí', () => {
        const slim = slimFeedVideo({
            id: 'a',
            channelId: 'UC1',
            sourceChannelId: 'UC1',
            musicReason: 'canal Topic de YouTube',
            liveBroadcastContent: 'none',
            defaultAudioLanguage: '',
            defaultLanguage: 'ca',
            contentType: 'song',
        });
        expect(slim).toEqual({ id: 'a', channelId: 'UC1', defaultLanguage: 'ca', contentType: 'song' });
        // home-sections.isOfficialClip llegeix aquest motiu
        expect(slimFeedVideo({ musicReason: 'marcador explícit de cançó/videoclip' }).musicReason).toBe(
            'marcador explícit de cançó/videoclip'
        );
        expect(slimFeedVideo({ channelId: 'UC1', sourceChannelId: 'UC2' }).sourceChannelId).toBe('UC2');
        expect(slimFeedVideo({ liveBroadcastContent: 'live' }).liveBroadcastContent).toBe('live');
    });

    it('escriu un vídeo per línia i es torna a llegir igual', () => {
        const feed = slimFeed({
            generatedAt: '2026-10-02T00:00:00.000Z',
            channels: { UC1: { name: 'Artista' } },
            videos: [
                { id: 'a', title: 'U', description: TOPIC },
                { id: 'b', title: 'Dos' },
            ],
        });
        const text = serializeFeed(feed);
        expect(JSON.parse(text)).toEqual(feed);
        const lines = text.split('\n');
        expect(lines.filter(line => line.startsWith('    {"id":'))).toHaveLength(2);
        expect(text.endsWith('}\n')).toBe(true);
        expect(JSON.parse(serializeFeed({ generatedAt: 'x', channels: {}, videos: [] }))).toEqual({
            generatedAt: 'x',
            channels: {},
            videos: [],
        });
    });
});
